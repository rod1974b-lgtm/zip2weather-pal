function detectInitialLanguage(): string {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem("weather:lang") || localStorage.getItem("app_language");
    if (saved && Object.prototype.hasOwnProperty.call(resources, saved)) {
      return saved;
    }
    const navLangs = navigator.languages || [navigator.language || ""];
    for (const lang of navLangs) {
      if (!lang) continue;
      const code = lang.toLowerCase().split("-")[0];
      if (code && Object.prototype.hasOwnProperty.call(resources, code)) {
        return code;
      }
    }
  } catch {}
  return "en";
}

const savedLang = detectInitialLanguage();

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang,
  fallbackLng: "en",
  interpolation: {
    escapeValue: false,
  },
  returnNull: false,
  returnEmptyString: false,
});

if (typeof window !== "undefined") {
  window.addEventListener("weather:lang-change", (e: any) => {
    const nextLang = e?.detail;
    if (nextLang && Object.prototype.hasOwnProperty.call(resources, nextLang)) {
      i18n.changeLanguage(nextLang);
      localStorage.setItem("weather:lang", nextLang);
      localStorage.setItem("app_language", nextLang);
      document.documentElement.lang = nextLang;
    }
  });
}

if (typeof document !== "undefined") {
  document.documentElement.lang = savedLang;
}

