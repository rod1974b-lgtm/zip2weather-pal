const getInitialLang = () => {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem("app_language") || localStorage.getItem("weather:lang");
    if (saved && resources[saved as keyof typeof resources]) return saved;

    const b = (navigator.languages?.[0] || navigator.language || "").toLowerCase();
    const prefix = b.split("-")[0];
    if (prefix && resources[prefix as keyof typeof resources]) return prefix;
  } catch {}
  return "en";
};

const formatMissingKey = (k: string) =>
  k
    .split("_")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");

const initialLang = getInitialLang();

i18n.use(initReactI18next).init({
  resources,
  lng: initialLang,
  fallbackLng: "en",
  debug: false,
  interpolation: { escapeValue: false },
  parseMissingKeyHandler: (k: string) => formatMissingKey(k),
  returnNull: false,
  returnEmptyString: false,
});

if (typeof document !== "undefined") {
  document.documentElement.lang = initialLang;
}

export default i18n;
